"""
Token Stream and Navigation Utilities (`gram.core.lexer.items`).
================================================================
Defines `TokenStream`, an iterable and inspectable wrapper around a sequence
of `TokenType` instances generated by the lexer.
"""
from __future__ import annotations

from collections.abc import Iterator, Sequence

from gram import errors
from gram.core.lexer.tokens import Token, TokenType


class TokenStream:
    """
    High-level wrapper over an ordered sequence of `TokenType` objects.

    Provides reading cursors, arbitrary lookahead, conditional consumption,
    and pattern matching helpers (`check`, `match`, `consume`).
    """

    __slots__ = ("_pos", "_tokens")

    def __init__(self, tokens: Sequence[TokenType]) -> None:
        self._tokens: tuple[TokenType, ...] = tuple(tokens)
        self._pos: int = 0

    @property
    def position(self) -> int:
        """Current cursor position in the token stream."""
        return self._pos

    @position.setter
    def position(self, pos: int) -> None:
        self._pos = max(0, min(pos, len(self._tokens)))

    @property
    def tokens(self) -> tuple[TokenType, ...]:
        """Immutable tuple of all tokens in the stream."""
        return self._tokens

    def has_next(self) -> bool:
        """Return True if unconsumed non-EOF tokens remain in the stream."""
        if self._pos >= len(self._tokens):
            return False
        return self._tokens[self._pos].token != Token.EOF

    def is_eof(self) -> bool:
        """Return True if the cursor has reached `Token.EOF` or the end of the stream."""
        if self._pos >= len(self._tokens):
            return True
        return self._tokens[self._pos].token == Token.EOF

    def current(self) -> TokenType | None:
        """Return the token at the current cursor position without consuming it."""
        if 0 <= self._pos < len(self._tokens):
            return self._tokens[self._pos]
        return None

    def peek(self, offset: int = 0) -> TokenType | None:
        """Inspect a token at a relative `offset` from the current cursor without advancing."""
        idx = self._pos + offset
        if 0 <= idx < len(self._tokens):
            return self._tokens[idx]
        return None

    def advance(self) -> TokenType:
        """Consume and return the current token, advancing the cursor by 1."""
        token = self.current()
        if token is None:
            line = (self._tokens[-1].line - 1) if self._tokens else 0
            col = self._tokens[-1].col if self._tokens else 0
            return TokenType(Token.EOF, None, line, col)
        self._pos += 1
        return token

    def next(self) -> TokenType:
        """Alias for `advance()`."""
        return self.advance()

    def check(self, *expected: Token | TokenType | str) -> bool:
        """Return True if the current token matches any of `expected` without advancing."""
        curr = self.current()
        if curr is None:
            return False

        for exp in expected:
            if isinstance(exp, Token) and curr.token == exp:
                return True
            if isinstance(exp, TokenType) and curr == exp:
                return True
            if isinstance(exp, str) and (curr.value == exp or curr.token.name == exp):
                return True
        return False

    def match(self, *expected: Token | TokenType | str) -> bool:
        """Consume the current token and return True if it matches any of `expected`."""
        if self.check(*expected):
            self.advance()
            return True
        return False

    def consume(
        self,
        expected: Token | TokenType | str | None = None,
        message: str = "",
    ) -> TokenType:
        """
        Consume and return the current token, verifying that it matches `expected`.

        Args:
            expected (Token | TokenType | str | None): Optional expected token specification.
            message (str): Custom error message on mismatch.

        Returns:
            TokenType: The consumed token.
        """
        curr = self.current()
        if curr is None:
            errors.ParserError(
                "EarlyStreamEOF",
                errors.PARSER_EARLY_EOF,
                message or "Se esperaba otro token pero se alcanzó el final de la secuencia.",
            ).raise_error()
        elif expected is not None and not self.check(expected):
            exp_str = expected.name if isinstance(expected, Token) else str(expected)
            errors.ParserError(
                f"UnexpectedStreamToken: {curr.token.name}",
                errors.PARSER_UNEXPECTED_TOKEN,
                message
                or (
                    f"Se esperaba el token {exp_str!r}, pero se encontró {curr.token.name!r} "
                    f"({curr.value!r}) en línea {curr.line}:{curr.col}."
                ),
            ).raise_error()

        return self.advance()

    def rewind(self, count: int = 1) -> None:
        """Move the cursor backward by `count` positions (clamped at 0)."""
        self._pos = max(0, self._pos - count)

    def reset(self) -> None:
        """Reset the cursor to the beginning of the stream (`0`)."""
        self._pos = 0

    def slice(self, start: int, end: int | None = None) -> list[TokenType]:
        """Return a list of tokens sliced between `start` and `end`."""
        return list(self._tokens[start:end])

    def filter_tokens(self, *exclude: Token) -> TokenStream:
        """Return a new `TokenStream` excluding any token whose type is in `exclude`."""
        exclude_set = set(exclude)
        return TokenStream([t for t in self._tokens if t.token not in exclude_set])

    def __len__(self) -> int:
        return len(self._tokens)

    def __iter__(self) -> Iterator[TokenType]:
        return iter(self._tokens)

    def __getitem__(self, index: int | slice) -> TokenType | list[TokenType]:
        if isinstance(index, slice):
            return list(self._tokens[index])
        return self._tokens[index]

    def __repr__(self) -> str:
        return f"TokenStream(tokens={len(self._tokens)}, current={self._pos})"


__all__ = ["TokenStream"]